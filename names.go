// toCP437 converts r to code page 437 the way RomVault does: printable
// ASCII maps to itself, and any other rune must match one of the glyphs
// for bytes 0x00-0x1f or 0x80-0xff. In particular the ASCII control
// characters 0x01-0x1f are not representable.
func toCP437(r rune) (byte, bool) {
	if 32 <= r && r <= 127 {
		return byte(r), true
	}

	c, ok := cp437Encode[r]

	return c, ok && (c < 32 || c >= 128)
}

// decodeCP437 decodes a name stored without the UTF-8 flag, as RomVault
// does when reading an archive.
func decodeCP437(name string) string {
	var sb strings.Builder

	for i := range len(name) {
		if c := name[i]; c < 32 || c >= 128 {
			sb.WriteRune(cp437[c])
		} else {
			sb.WriteByte(c)
		}
	}

	return sb.String()
}

// encodeName returns the bytes to store for name and whether the UTF-8
// flag must be set. Names that can be represented in code page 437 are
// stored that way, as the original TorrentZip and RomVault do; anything
// else is stored as UTF-8.
func encodeName(name string) ([]byte, bool) {
	if !utf8.ValidString(name) {
		// Not valid UTF-8, so store the bytes as given.
		return []byte(name), false
	}

	b := make([]byte, 0, len(name))
	for _, r := range name {
		c, ok := toCP437(r)
		if !ok {
			return []byte(name), true
		}

		b = append(b, c)
	}

	return b, false
}
