package torrentzip

import (
	"strings"
	"unicode/utf16"
	"unicode/utf8"
)

// CompareNames compares two file names using the TorrentZip ordering and
// returns -1, 0 or +1. Names are compared as UTF-16 code units with ASCII
// letters folded to lower case; names that are equal ignoring case are then
// ordered by their exact code units.
func CompareNames(a, b string) int {
	if c := compareUTF16(a, b, true); c != 0 {
		return c
	}

	return compareUTF16(a, b, false)
}

func compareUTF16(a, b string, fold bool) int {
	ia, ib := utf16Iter{s: a}, utf16Iter{s: b}
	for {
		ca, oka := ia.next()

		cb, okb := ib.next()
		switch {
		case !oka && !okb:
			return 0
		case !oka:
			return -1
		case !okb:
			return 1
		}

		if fold {
			ca, cb = lowerASCII(ca), lowerASCII(cb)
		}

		if ca != cb {
			if ca < cb {
				return -1
			}

			return 1
		}
	}
}

func lowerASCII(c uint16) uint16 {
	if 'A' <= c && c <= 'Z' {
		return c + 'a' - 'A'
	}

	return c
}

// utf16Iter yields the UTF-16 code units of a UTF-8 string.
type utf16Iter struct {
	s     string
	trail uint16
}

func (it *utf16Iter) next() (uint16, bool) {
	if it.trail != 0 {
		c := it.trail
		it.trail = 0

		return c, true
	}

	if it.s == "" {
		return 0, false
	}

	r, n := utf8.DecodeRuneInString(it.s)
	it.s = it.s[n:]

	var buf [2]uint16

	u := utf16.AppendRune(buf[:0], r)
	if len(u) == 2 {
		it.trail = u[1]
	}

	return u[0], true
}

// hasPrefixFold reports whether s begins with prefix, ignoring the case of
// ASCII letters.
func hasPrefixFold(s, prefix string) bool {
	if len(s) < len(prefix) {
		return false
	}

	for i := range len(prefix) {
		if lowerASCII(uint16(s[i])) != lowerASCII(uint16(prefix[i])) {
			return false
		}
	}

	return true
}

func isDir(name string) bool {
	return strings.HasSuffix(name, "/")
}

